function sanitizeQueries(list) {
  const out = []
  const seen = new Set()
  for (const raw of list) {
    const q = typeof raw === 'string' ? raw.trim() : ''
    if (q.length < 3) continue
    const key = q.toLowerCase()
    if (seen.has(key)) continue
    seen.add(key)
    out.push(q)
  }
  return out
}

module.exports.CATALOG_SEARCH_QUERIES = sanitizeQueries(CATALOG_RAW)
